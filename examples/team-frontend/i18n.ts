export type TextKey = keyof typeof nb;

const catalogues: Record<Language, typeof nb> = { nb, en };

export const text = (language: Language | undefined, key: TextKey) =>
  catalogues[language ?? 'nb'][key];

export const languageOf = (value: string | null | undefined): Language =>
  languages.find((l) => l === value) ?? 'nb';
