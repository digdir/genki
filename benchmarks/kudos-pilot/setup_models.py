"""Prepare the Kudos pilot's model comparison (genki issue 92) from models.json:

- .data/config: a copy of apps/api/config/local plus, per model, an embedding endpoint (its embed_server.py), an
  embedding model with the model's prompts, a dataset digdir/kudos-next-<key> and a retrieve-only service
  kudos-pilot-<key>-retrieve-only, with a -noplan twin that searches with the question as asked (planner.enabled
  false: no model call, so it costs nothing). The baseline gets kudos-pilot-noplan-retrieve-only. The committed
  config stays as it is; the per-model APIs run with CONFIG_DIR.
- Per model, a platform database genai_<key> and a knowledge database knowledge_<key> on the pilot's two Postgres
  containers, the knowledge one with a copy of src_conversions so the ingest reuses the stored Marker output.

    .data/embed-venv/bin/python setup_models.py [key ...]      # every model in models.json by default

Needs the pilot containers (genki-kudos-pilot-postgres-1, genki-kudos-pilot-knowledge-1) running. Rerunning it
rewrites the config and leaves databases that exist alone.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

from common import DATA, REPO

HERE = Path(__file__).resolve().parent
CONFIG = DATA / "config"
PLATFORM = "genki-kudos-pilot-postgres-1"
KNOWLEDGE = "genki-kudos-pilot-knowledge-1"


def models(keys):
    listed = json.loads((HERE / "models.json").read_text())["models"]
    return [m for m in listed if not keys or m["key"] in keys]


def database_name(prefix, model):
    return f"{prefix}_{model['key'].replace('-', '_')}"


def psql(container, database, sql):
    return subprocess.run(
        ["docker", "exec", container, "psql", "-U", "genai", "-d", database, "-Atc", sql],
        check=True, capture_output=True, text=True,
    ).stdout.strip()


def ensure_database(container, name):
    if psql(container, "postgres", f"select 1 from pg_database where datname = '{name}'") == "1":
        return False
    psql(container, "postgres", f"create database {name}")
    return True


def copy_conversions(name):
    # The table and its rows from the pilot's knowledge database, so no PDF goes to Marker again
    dump = subprocess.run(
        ["docker", "exec", KNOWLEDGE, "pg_dump", "-U", "genai", "-d", "knowledge", "-t", "src_conversions"],
        check=True, capture_output=True,
    ).stdout
    subprocess.run(
        ["docker", "exec", "-i", KNOWLEDGE, "psql", "-U", "genai", "-d", name, "-q", "-v", "ON_ERROR_STOP=1"],
        input=dump, check=True, capture_output=True,
    )


def write_service(service, name):
    service["metadata"]["id"] = name
    (CONFIG / "services" / f"{name}.yaml").write_text(
        f"# Generated by benchmarks/kudos-pilot/setup_models.py\n{yaml.safe_dump(service, allow_unicode=True, sort_keys=False)}"
    )


def without_planner(service):
    copy = json.loads(json.dumps(service))
    copy["metadata"]["name"] = f"{copy['metadata']['name']}, uten planlegging"
    copy["spec"]["settings"] = {**copy["spec"].get("settings", {}), "planner.enabled": False}
    return copy


def write_config(chosen):
    if CONFIG.exists():
        shutil.rmtree(CONFIG)
    shutil.copytree(REPO / "apps" / "api" / "config" / "local", CONFIG)
    embeddings = yaml.safe_load((CONFIG / "embeddings.yaml").read_text())
    knowledge = yaml.safe_load((CONFIG / "knowledge.yaml").read_text())
    template = yaml.safe_load((CONFIG / "services" / "kudos-pilot-retrieve-only.yaml").read_text())
    for m in chosen:
        embeddings["endpoints"][f"local-{m['key']}"] = {
            "protocol": "openai-embeddings",
            "baseURL": f"http://127.0.0.1:{m['server']}/v1",
            "auth": {"kind": "api-key", "secret": "secret://env/local-embeddings-key"},
        }
        embeddings["models"].append({
            "id": f"local/{m['key']}",
            "endpoint": f"local-{m['key']}",
            "deployment": m["hf"],
            "residency": "norway",
            "dimensions": m["dimensions"],
            "maxBatch": m["maxBatch"],
            **({"prompts": m["prompts"]} if m["prompts"] else {}),
        })
        knowledge["datasets"].append({
            "id": f"digdir/kudos-next-{m['key']}",
            "name": f"Kudos på pgvector, {m['hf']} (pilot)",
            "description": f"Kudos-piloten med vektorer fra {m['hf']}, kjørt lokalt",
            "endpoint": "platform-pg",
            "residency": "norway",
            "embedding": {"model": f"local/{m['key']}", "dimensions": m["dimensions"]},
        })
        service = json.loads(json.dumps(template))
        service["metadata"]["id"] = f"kudos-pilot-{m['key']}-retrieve-only"
        service["metadata"]["name"] = f"Kudos-piloten, {m['hf']}, bare søk"
        service["spec"]["knowledge"]["datasets"] = [{"dataset": f"digdir/kudos-next-{m['key']}"}]
        write_service(service, f"kudos-pilot-{m['key']}-retrieve-only")
        write_service(without_planner(service), f"kudos-pilot-{m['key']}-noplan-retrieve-only")
    write_service(without_planner(json.loads(json.dumps(template))), "kudos-pilot-noplan-retrieve-only")
    for name, data in (("embeddings.yaml", embeddings), ("knowledge.yaml", knowledge)):
        (CONFIG / name).write_text(
            f"# Generated by benchmarks/kudos-pilot/setup_models.py from apps/api/config/local\n"
            f"{yaml.safe_dump(data, allow_unicode=True, sort_keys=False)}"
        )


def main():
    every = models([])
    chosen = models(sys.argv[1:])
    write_config(every)
    print(f"wrote {CONFIG} with {len(every)} local models")
    for m in chosen:
        platform, knowledge = database_name("genai", m), database_name("knowledge", m)
        made = ensure_database(PLATFORM, platform)
        if ensure_database(KNOWLEDGE, knowledge):
            copy_conversions(knowledge)
            made = True
        count = psql(KNOWLEDGE, knowledge, "select count(*) from src_conversions")
        print(f"{m['key']}: {platform}, {knowledge} ({'created' if made else 'existed'}; {count} stored conversions)")


if __name__ == "__main__":
    main()
