  scopeUnordered: {
    one: 'Her er utdraget som ble hentet fra dokumentet. Resten av dokumentet er ikke med her.',
    other:
      'Her er de {count} utdragene som ble hentet fra dokumentet. Resten av dokumentet er ikke med her.',
  },
  disclaimer: 'All tekst er sitater fra dokumentet. Ikke generert av kunstig intelligens.',
  gap: 'Tekst som ikke er med',
  steps: 'Utdrag i dokumentet',
  position: '{n} av {total}',
  count: { one: '{count} utdrag', other: '{count} utdrag' },
