export const readVersion = (
  value: string | undefined,
): { version?: number } | { error: string } => {
  if (value === undefined || value.trim() === '') return {};
  const trimmed = value.trim();
  return /^[1-9]\d{0,8}$/.test(trimmed)
    ? { version: Number(trimmed) }
    : { error: '`GenAI-Version` must be a positive whole number.' };
};

export const readPin = (
  header: string | undefined,
  body: Record<string, unknown>,
): { version?: number } | { error: string } => {
  const fromHeader = readVersion(header);
  if ('error' in fromHeader) return fromHeader;
  const raw = isRecord(body.metadata) ? body.metadata.version : undefined;
  if (raw === undefined) return fromHeader;
  const fromBody =
    typeof raw === 'string' || typeof raw === 'number' ? readVersion(String(raw)) : { error: '' };
  if ('error' in fromBody) return { error: '`metadata.version` must be a positive whole number.' };
  if (
    fromHeader.version !== undefined &&
    fromBody.version !== undefined &&
    fromHeader.version !== fromBody.version
  )
    return {
      error: `\`GenAI-Version\` asks for version ${fromHeader.version} and \`metadata.version\` for version ${fromBody.version}. Send one version.`,
    };
  return fromBody.version === undefined ? fromHeader : fromBody;
};

