const documentLinks = (records: SourceRecord[]) => {
  const seen = new Set<string>();
  return records.flatMap((r) => {
    const key = r.document ?? r.chunkId;
    if (seen.has(key)) return [];
    seen.add(key);
    const excerpt = excerptOf(r.text);
    return [
      {
        uri: publicSourceUrl(r) ?? `digdir://doc/${r.document ?? r.chunkId}`,
        name: r.title ?? 'Untitled source',
        ...(excerpt === undefined ? {} : { excerpt }),
        ...provenanceOf(r),
      },
    ];
  });
};

