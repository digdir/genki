import { z } from 'zod';
import type { Consumer, PlatformSetting } from './platform-settings.js';
import type { Layer } from './settings.js';

const runtimeLayers: Layer[] = ['platform', 'tenant', 'service', 'call'];
const nullable = <T extends z.ZodType>(schema: T) => schema.nullable();
const positiveInt = z.number().int().positive();

const retrieval = (field: string): Consumer => ({
  package: '@genai/retrieval',
  field: `retrievalConfig.${field}`,
});
const planner = (field: string): Consumer => ({
  package: '@genai/retrieval',
  field: `plannerConfig.${field}`,
});
const agentLoop = (field: string): Consumer => ({
  package: '@genai/strategy-agent-loop',
  field: `agentLoopConfig.${field}`,
});
const rag = (field: string): Consumer => ({
  package: '@genai/strategy-rag',
  field: `ragConfig.${field}`,
});

const setting = <T>(
  key: string,
  schema: z.ZodType<T>,
  defaultValue: T,
  category: string,
  description: string,
  consumers: Consumer[],
): PlatformSetting<T> => ({
  key,
  schema,
  default: defaultValue,
  category,
  description,
  consumers,
  axis: 'service',
  sensitivity: 'normal',
  settableAt: runtimeLayers,
});

